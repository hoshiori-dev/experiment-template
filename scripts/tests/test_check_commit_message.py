import pytest

import check_commit_message as ccm

GOOD = "scripts: add budget check\n\nCount reserved amounts on unmerged run branches.\n"
AT = "@"  # addresses are assembled at runtime so this file holds no literal email


@pytest.fixture(autouse=True)
def noreply_author(monkeypatch):
    monkeypatch.setenv("GIT_AUTHOR_EMAIL", "1+tester@users.noreply.github.com")


def check(text: str) -> list[str]:
    return ccm.check_message(text, "msg")


def test_good_message_passes():
    assert check(GOOD) == []
    assert check("scripts: add budget check\n") == []


def test_comments_and_scissors_are_ignored():
    text = (
        GOOD + "# Please enter the commit message\n# ------------------------ >8 ------------------------\ndiff --git\n"
    )
    assert check(text) == []


@pytest.mark.parametrize(
    ("title", "expected"),
    [
        ("scripts: " + "x" * 50, "title has 59 characters"),
        ("Add budget check", "'<scope>: <summary>'"),
        ("scripts: Add budget check", "'<scope>: <summary>'"),
        ("scripts: add budget check.", "'<scope>: <summary>'"),
        ("scripts: add budget chéck", "title must be ASCII"),
    ],
)
def test_title_rules(title, expected):
    assert expected in "\n".join(check(title + "\n"))


def test_merge_fixup_and_squash_skip_title_rules():
    assert check("Merge pull request #12 from owner/exp-023-normalization-instability-long-name\n") == []
    assert check("fixup! scripts: add budget check\n") == []
    assert check("squash! scripts: Add budget check\n") == []


def test_body_layout():
    assert "second line must be blank" in check("scripts: add x\nbody right away\n")[0]
    long = "scripts: add x\n\n" + "word " * 20 + "\n"
    assert "wrap at 72" in check(long)[0]
    url = "scripts: add x\n\nhttps://example.invalid/" + "a" * 90 + "\n"
    assert check(url) == []


@pytest.mark.parametrize(
    "trailer",
    [
        f"Co-Authored-By: Claude <noreply{AT}anthropic.com>",
        f"Co-authored-by: Codex <codex{AT}users.noreply.github.com>",
        f"Co-Authored-By: GitHub Copilot <copilot{AT}github.com>",
        f"Co-Authored-By: some-bot[bot] <1+bot{AT}users.noreply.github.com>",
        f"Co-Authored-By: Gemini Agent <agent{AT}users.noreply.github.com>",
    ],
)
def test_agent_coauthors_are_rejected(trailer):
    assert "credits an agent" in check(GOOD + "\n" + trailer + "\n")[0]


@pytest.mark.parametrize("line", ["Generated with Claude Code", "generated by a tool", "\U0001f916 done"])
def test_generated_footers_are_rejected(line):
    assert "attributes the commit to a tool" in check(GOOD + "\n" + line + "\n")[0]


def test_human_coauthor_needs_noreply_address():
    assert check(GOOD + f"\nCo-Authored-By: Ada <2+ada{AT}users.noreply.github.com>\n") == []
    assert check(GOOD + f"\nCo-authored-by: Ada <3-ada{AT}noreply.gitlab.com>\n") == []
    assert "noreply.gitlab.com address" in check(GOOD + f"\nCo-Authored-By: Ada <ada{AT}example.com>\n")[0]


def test_author_address(monkeypatch):
    assert ccm.check_author("msg") == []
    monkeypatch.setenv("GIT_AUTHOR_EMAIL", f"ada{AT}example.com")
    assert "not a platform noreply address" in ccm.check_author("msg")[0]
    monkeypatch.setattr(ccm, "REQUIRE_NOREPLY_AUTHOR", False)
    assert ccm.check_author("msg") == []


def test_author_from_git_var(monkeypatch, repo):
    monkeypatch.delenv("GIT_AUTHOR_EMAIL")
    repo.git("config", "user.email", f"ada{AT}example.com")
    assert "not a platform noreply address" in ccm.check_author("msg")[0]


def test_cli(tmp_path, capsys):
    msg = tmp_path / "COMMIT_EDITMSG"
    msg.write_text(GOOD)
    assert ccm.main([str(msg)]) == 0
    msg.write_text(f"Bad title\n\nCo-Authored-By: Claude <noreply{AT}anthropic.com>\n")
    assert ccm.main([str(msg)]) == 1
    out = capsys.readouterr().out
    assert out.count("COMMIT_EDITMSG: ") == 2
    assert ccm.main([str(tmp_path / "missing")]) == 2

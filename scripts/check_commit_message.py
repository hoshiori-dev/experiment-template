"""Commit-msg hook: no agent attribution, 50/72 layout, scope-prefixed title, noreply author.

Usage: check_commit_message.py <msg-file>

Rejects Co-Authored-By trailers naming an agent (claude, codex, opencode, copilot, gemini,
gpt, anthropic, openai, bot, agent), "Generated with", "Generated by" and the robot emoji.
Requires a title of at most 50 ASCII characters shaped ``<scope>: <summary>`` with a
lowercase summary and no trailing period, a blank second line, and body lines of at most
72 characters (a line without spaces, such as a URL, may be longer). Human Co-Authored-By
trailers need a ``users.noreply.github.com`` or ``noreply.gitlab.com`` address. The author
address (``GIT_AUTHOR_EMAIL``, else ``git var GIT_AUTHOR_IDENT``) must be a noreply address
while ``REQUIRE_NOREPLY_AUTHOR`` is True. Merge commits and fixup!/squash! titles skip the
title rules.

Exit codes: 0 accepted; 1 rejected (each reason printed); 2 message file unreadable.
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
from pathlib import Path

AGENT_WORDS = re.compile(r"\b(claude|codex|opencode|copilot|gemini|gpt|anthropic|openai|bot|agent)\b", re.I)
COAUTHOR_RE = re.compile(r"^co-authored-by:\s*(.*)$", re.I)
GENERATED_RE = re.compile(r"generated (with|by)|\U0001F916", re.I)
TITLE_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._/-]*: [a-z].*[^.]$")
NOREPLY_SUFFIXES = ("users.noreply.github.com", "noreply.gitlab.com")
# Owners who allow other author addresses flip this to False in a preparation-phase PR.
REQUIRE_NOREPLY_AUTHOR = True
SCISSORS = "# ------------------------ >8 ------------------------"
TITLE_LIMIT = 50
BODY_LIMIT = 72


def message_lines(text: str) -> list[str]:
    """Message lines as git will keep them: comments and anything after the scissors dropped."""
    kept = []
    for line in text.splitlines():
        if line.startswith(SCISSORS):
            break
        if not line.startswith("#"):
            kept.append(line.rstrip())
    while kept and not kept[0].strip():
        kept.pop(0)
    while kept and not kept[-1].strip():
        kept.pop()
    return kept


def is_noreply(email: str) -> bool:
    return email.lower().endswith(NOREPLY_SUFFIXES)


def check_message(text: str, label: str) -> list[str]:
    lines = message_lines(text)
    if not lines:
        return [f"{label}: message is empty"]
    findings = []
    title = lines[0]
    exempt = title.startswith(("Merge ", "fixup! ", "squash! "))
    if not exempt:
        if len(title) > TITLE_LIMIT:
            findings.append(f"{label}: title has {len(title)} characters; keep it at most {TITLE_LIMIT}")
        if not title.isascii():
            findings.append(f"{label}: title must be ASCII")
        elif not TITLE_RE.match(title):
            findings.append(
                f"{label}: title must read '<scope>: <summary>' with a lowercase summary and no trailing period"
            )
    if len(lines) > 1 and lines[1].strip():
        findings.append(f"{label}: second line must be blank")
    for number, line in enumerate(lines[1:], start=2):
        if len(line) > BODY_LIMIT and " " in line.strip():
            findings.append(f"{label}: line {number} has {len(line)} characters; wrap at {BODY_LIMIT}")
    for number, line in enumerate(lines, start=1):
        if GENERATED_RE.search(line):
            findings.append(f"{label}: line {number} attributes the commit to a tool; remove it")
        trailer = COAUTHOR_RE.match(line.strip())
        if not trailer:
            continue
        value = trailer.group(1)
        if AGENT_WORDS.search(value):
            findings.append(f"{label}: line {number} credits an agent as co-author; remove the trailer")
            continue
        email = re.search(r"<([^>]+)>", value)
        if not email or not is_noreply(email.group(1)):
            findings.append(
                f"{label}: line {number} co-author needs a users.noreply.github.com or noreply.gitlab.com address"
            )
    return findings


def author_email() -> str | None:
    email = os.environ.get("GIT_AUTHOR_EMAIL")
    if email:
        return email
    result = subprocess.run(["git", "var", "GIT_AUTHOR_IDENT"], capture_output=True, text=True, check=False)
    match = re.search(r"<([^>]*)>", result.stdout)
    return match.group(1) if match else None


def check_author(label: str) -> list[str]:
    if not REQUIRE_NOREPLY_AUTHOR:
        return []
    email = author_email()
    if email is None:
        return [f"{label}: cannot determine the author address; set GIT_AUTHOR_EMAIL or user.email"]
    if not is_noreply(email):
        return [
            f"{label}: author address is not a platform noreply address; set user.email to "
            "<id>+<login>@users.noreply.github.com"
        ]
    return []


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[1])
    parser.add_argument("msg_file", type=Path, metavar="msg-file")
    args = parser.parse_args(argv)
    label = args.msg_file.as_posix()
    try:
        text = args.msg_file.read_text(encoding="utf-8")
    except OSError as error:
        print(f"{label}: cannot read message file ({error})")
        return 2
    findings = check_message(text, label) + check_author(label)
    for finding in findings:
        print(finding)
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main())
